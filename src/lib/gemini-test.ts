// 테스트용 AI 응답 함수 (실제 API 없이 동작)
export async function generateTestAIResponse(prompt: string): Promise<string> {
  // 실제 Gemini API 대신 테스트 응답 제공
  await new Promise(resolve => setTimeout(resolve, 1000)) // 1초 지연으로 실제 API 호출처럼 보이게
  
  const message = prompt.toLowerCase()
  
  // 키워드 기반 응답 매칭
  if (message.includes('수면') || message.includes('잠')) {
    return `수면 패턴에 대해 걱정이 많으시군요. 

아기의 수면 패턴은 나이에 따라 달라집니다:

**신생아 (0-3개월)**
- 하루 14-17시간 수면
- 2-3시간마다 깨어남
- 밤낮 구분이 어려움

**영아기 (4-11개월)**  
- 하루 12-15시간 수면
- 밤에 6-8시간 연속 수면 가능
- 낮잠 2-3회

**개선 방법:**
1. 규칙적인 수면 루틴 만들기
2. 침실 환경 어둡고 조용하게 유지
3. 낮에는 충분한 자연광 노출

혹시 구체적으로 어떤 부분이 걱정되시나요? (자주 깨는 것, 잠들기 어려워하는 것 등)`
  }
  
  if (message.includes('식사') || message.includes('밥') || message.includes('이유식')) {
    return `식사와 관련된 걱정이시군요.

**월령별 식사 가이드:**

**0-6개월:** 모유 또는 분유만
**6개월:** 이유식 시작 (곡물 위주)
**7-8개월:** 과일, 채소 추가
**9-12개월:** 단백질, 핑거푸드

**식사 거부 대처법:**
1. 강요하지 않기
2. 다양한 식감과 맛 경험시키기
3. 가족과 함께 식사하기
4. 놀이처럼 재미있게 접근

아이가 몇 개월인지, 어떤 부분이 어려우신지 알려주시면 더 구체적인 조언을 드릴 수 있어요.`
  }
  
  if (message.includes('발달') || message.includes('마일스톤') || message.includes('늦')) {
    return `아이의 발달에 대한 걱정이시군요.

**주요 발달 마일스톤:**

**3개월:** 목 가누기, 미소 짓기
**6개월:** 뒤집기, 앉기 시도
**9개월:** 기기, 잡고 서기
**12개월:** 걸음마, 간단한 단어

**기억해주세요:**
- 개인차가 2-3개월 정도는 정상
- 전체적인 발달 패턴이 중요
- 퇴행하지 않는다면 대부분 정상

**발달을 돕는 방법:**
1. 충분한 바닥 놀이 시간
2. 다양한 자극과 경험 제공
3. 아이와 많은 대화하기

혹시 몇 개월 아기이고 어떤 발달이 걱정되시나요?`
  }
  
  if (message.includes('울음') || message.includes('울어') || message.includes('보채')) {
    return `아기 울음으로 힘드시겠어요.

**울음의 주요 원인:**
1. 배고픔 (가장 흔한 원인)
2. 기저귀가 젖음
3. 피곤함
4. 너무 덥거나 추움
5. 트림이 필요함
6. 자극 과다 (영아산통)

**달래는 방법:**
- 스와들링 (포대기로 감싸기)
- 흔들어주기 (부드럽게)
- 슉슉 소리 내기
- 젖꼭지 주기
- 옆으로 눕혀 안기

**영아산통인 경우:**
- 생후 2주~4개월에 흔함
- 저녁에 주로 발생
- 3주 이상 지속되면 소아과 상담

언제, 어떻게 우는지 패턴을 관찰해보시면 원인을 찾는 데 도움이 됩니다.`
  }
  
  // 기본 응답들
  const generalResponses = [
    "안녕하세요! 육아 전문 AI입니다. 구체적인 질문을 해주시면 더 도움이 되는 답변을 드릴 수 있어요.",
    "아이의 나이와 구체적인 상황을 알려주시면 더 정확한 조언을 드릴 수 있습니다.",
    "육아는 정답이 없는 여정입니다. 아이를 잘 관찰하시고, 필요시 전문의와 상담받으세요.",
    "궁금한 점이 있으시면 언제든 물어보세요. 수면, 식사, 발달, 건강 등 어떤 주제든 도움드리겠습니다."
  ]
  
  return generalResponses[Math.floor(Math.random() * generalResponses.length)]
}